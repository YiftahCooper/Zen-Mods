import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
const modules=['state','pin-engine','zones','controls','presentation','terminology','settings','controller'];
let bundle='// Generated by scripts/build.mjs. Edit src/*.mjs instead.\n';
for(const name of modules){const code=readFileSync(new URL(`../src/${name}.mjs`,import.meta.url),'utf8').replace(/^import .*?;\r?\n/gm,'');bundle+=`\n// ---- ${name} ----\n${code}\n`;}
bundle+='\nif (typeof window !== "undefined") void bootstrap(window);\n';
writeFileSync(new URL('better-pins.uc.mjs',import.meta.url),bundle);
const files=['theme.json','preferences.json','chrome.css','scripts/better-pins.uc.mjs'];
const hashes=Object.fromEntries(files.map(file=>[file,createHash('sha256').update(readFileSync(new URL('../'+file,import.meta.url))).digest('hex')]));
mkdirSync(new URL('../artifacts/',import.meta.url),{recursive:true});
writeFileSync(new URL('../artifacts/package-identity.json',import.meta.url),JSON.stringify({version:JSON.parse(readFileSync(new URL('../theme.json',import.meta.url),'utf8')).version,files:hashes},null,2)+'\n');
console.log('Built Better Pins candidate; package identity saved.');
