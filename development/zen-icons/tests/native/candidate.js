const done=arguments[arguments.length-1];
(async()=>{
  const w=Services.wm.getMostRecentWindow('navigator:browser');
  const sleep=ms=>new Promise(resolve=>w.setTimeout(resolve,ms));
  const wait=async(fn,label)=>{for(let i=0;i<300;i++){if(fn())return;await sleep(100);}throw Error('Timeout: '+label);};
  await wait(()=>w.gBrowser && w.gZenWorkspaces && w.document.getElementById('PanelUI-zen-emojis-picker')?.hasAttribute('zen-icons-enhanced'),'Sine/Icons startup');
  const checks=[];
  const check=(name,value,detail)=>{checks.push({name,passed:Boolean(value),detail});if(!value)throw Error(name+': '+JSON.stringify(detail));};
  const doc=w.document,panel=doc.getElementById('PanelUI-zen-emojis-picker');
  check('packaged runtime activated',true);
  const tab=w.gBrowser.addTab('about:blank',{skipAnimation:true,triggeringPrincipal:Services.scriptSecurityManager.getSystemPrincipal()});
  w.gBrowser.selectedTab=tab;
  const open=async()=>{
    w.document.getElementById('context_zen-edit-tab-icon') && (w.TabContextMenu.contextTab=tab);
    w.gZenEmojiPicker.open(tab.iconImage,{emojiAsSVG:true,closeOnSelect:false,onSelect:icon=>{if(icon)tab.zenStaticIcon=icon;else delete tab.zenStaticIcon;w.gBrowser.setIcon(tab,icon);}});
    await wait(()=>doc.getElementById('zen-icons-sine-root'),'picker ready');await sleep(150);
    return doc.getElementById('zen-icons-sine-root');
  };
  let root=await open();
  check('Reset Icon labelled action',root.querySelector('.zen-icons-reset-tab-icon')?.textContent.trim()==='Reset Icon');
  check('default tab square present',Boolean(root.querySelector('.zen-icons-native-tab-placeholder')));
  root.querySelector('.zen-icons-default-choice').click();
  check('default tab square persists native override',tab.zenStaticIcon==='chrome://sine/content/zen-icons-local/blank-tab.svg',tab.zenStaticIcon);
  const search=root.querySelector('.zen-icons-search');search.value='dog';search.dispatchEvent(new w.Event('input',{bubbles:true}));await sleep(150);
  const dog=[...root.querySelectorAll('[data-icon-id]')].find(b=>b.dataset.iconId==='lucide:dog');
  check('tagged Lucide search',Boolean(dog));dog.click();
  check('native tab selection callback',String(tab.zenStaticIcon).includes('/display-lucide/dog.svg'),tab.zenStaticIcon);
  panel.hidePopup();await sleep(150);
  Services.prefs.setBoolPref('zen-icons.tab.use-space-colour',false);
  await sleep(100);
  check('neutral default setting updates immediately',doc.documentElement.hasAttribute('zen-icons-neutral-tab-default'));
  Services.prefs.setBoolPref('zen-icons.double-click-icons',true);await sleep(100);
  tab.iconImage.dispatchEvent(new w.MouseEvent('dblclick',{button:0,detail:2,bubbles:true,cancelable:true}));
  await wait(()=>doc.getElementById('zen-icons-sine-root'),'double click picker');
  check('tab icon double click opens real picker',Boolean(doc.getElementById('zen-icons-sine-root')));
  check('tab survives native double click',tab.isConnected && !tab.closing);
  panel.hidePopup();await sleep(100);
  const folder=await w.gZenFolders.createFolder([tab],{renameFolder:false,label:'Icons Candidate',insertBefore:tab});
  await sleep(150);w.gZenFolders.changeFolderUserIcon(folder);
  await wait(()=>doc.getElementById('zen-icons-sine-root'),'folder picker');root=doc.getElementById('zen-icons-sine-root');
  const folderSearch=root.querySelector('.zen-icons-search');folderSearch.value='dog';folderSearch.dispatchEvent(new w.Event('input',{bubbles:true}));await sleep(150);
  const folderDog=[...root.querySelectorAll('[data-icon-id]')].find(b=>b.dataset.iconId==='lucide:dog');
  check('folder Lucide result',Boolean(folderDog));folderDog.click();await sleep(100);
  const href=folder.querySelector(':scope > .tab-group-label-container > .tab-group-folder-icon svg .icon image')?.getAttribute('href');
  check('folder icon projects to actual SVG',String(href).includes('dog.svg'),href);
  const reset=root.querySelector('.zen-icons-default-choice');reset.click();await sleep(100);
  check('folder default reenables outline',!folder.hasAttribute('zen-icons-hide-folder-shape'));
  panel.hidePopup();await sleep(100);
  folder.icon.dispatchEvent(new w.MouseEvent('dblclick',{button:0,detail:2,bubbles:true,cancelable:true}));
  await wait(()=>doc.getElementById('zen-icons-sine-root'),'folder double click');
  check('folder double click opens real picker',true);panel.hidePopup();
  return {passed:true,version:Services.appinfo.version,buildId:Services.appinfo.appBuildID,checks};
})().then(done,error=>done({passed:false,error:String(error),stack:error.stack}));
