const done=arguments[arguments.length-1];
(async()=>{
  const w=Services.wm.getMostRecentWindow('navigator:browser');
  const pause=ms=>new Promise(r=>w.setTimeout(r,ms));
  const wait=async(fn,label)=>{for(let i=0;i<200;i++){if(fn())return;await pause(100);}throw Error('Timeout '+label);};
  await wait(()=>w.document.getElementById('PanelUI-zen-emojis-picker')?.hasAttribute('zen-icons-enhanced'),'Icons');
  const tab=w.gBrowser.addTrustedTab('about:preferences#sineMods');w.gBrowser.selectedTab=tab;
  await wait(()=>tab.linkedBrowser.contentDocument?.getElementById('sineModsList'),'Sine settings document');
  const doc=tab.linkedBrowser.contentDocument;
  await wait(()=>doc.getElementById('sineModsList')?.textContent.includes('Zen Icons'),'Icons settings row');
  const mod=doc.getElementById('zen-icons-local') || [...doc.querySelectorAll('#sineModsList > *')].find(n=>n.textContent.includes('Zen Icons'));
  if(!mod)throw Error('Missing Icons settings entry');
  const checks=[],check=(name,ok,detail)=>{checks.push({name,passed:Boolean(ok),detail});if(!ok)throw Error(name+': '+JSON.stringify(detail));};
  mod.querySelector('.sineItemConfigureButton').click();
  const heading=doc.getElementById('zen-icons-tab-heading').querySelector('.separator-label');
  const style=doc.defaultView.getComputedStyle(heading);
  check('settings section heading is larger and bold',style.fontSize==='18px' && Number(style.fontWeight)>=600,{size:style.fontSize,weight:style.fontWeight});
  const shell=doc.getElementById('zen-icons-tab-show-emoji');shell.click();
  check('native Sine checkbox updates saved tab default',Services.prefs.getBoolPref('zen-icons.tab.show-emoji')===false);
  check('other picker defaults stay independent',Services.prefs.getBoolPref('zen-icons.folder.show-emoji',true) && Services.prefs.getBoolPref('zen-icons.space.show-emoji',true));
  w.gZenEmojiPicker.open(tab.iconImage,{emojiAsSVG:true,closeOnSelect:false,onSelect(){}});
  await wait(()=>w.document.getElementById('zen-icons-sine-root'),'picker for defaults');
  let root=w.document.getElementById('zen-icons-sine-root');
  const emoji=w.document.querySelector('[data-provider="emoji"]');emoji.checked=true;emoji.dispatchEvent(new w.Event('change',{bubbles:true}));
  w.document.querySelector('.zen-icons-save-defaults').click();await pause(80);
  check('Save as Defaults refreshes an already-open Sine checkbox',shell.getAttribute('checked')==='true' && shell.querySelector('checkbox').checked===true);
  shell.click();check('refreshed Sine checkbox turns off with one click',Services.prefs.getBoolPref('zen-icons.tab.show-emoji')===false);
  const colour=doc.getElementById('zen-icons-tab-use-space-colour');colour.click();await pause(60);
  check('native settings can enable neutral default icons',w.document.documentElement.hasAttribute('zen-icons-neutral-tab-default'));
  const gestures=doc.getElementById('zen-icons-double-click-icons');gestures.click();await pause(60);
  check('native settings enable double-click gestures',w.document.documentElement.hasAttribute('zen-icons-double-click-enabled'));
  w.document.getElementById('PanelUI-zen-emojis-picker').hidePopup();
  const toggle=mod.querySelector('.sineItemPreferenceToggle');
  toggle.click();
  await wait(()=>!w.document.getElementById('PanelUI-zen-emojis-picker').hasAttribute('zen-icons-enhanced'),'Icons disable cleanup');
  check('Sine disable removes runtime and gesture markers',!w.document.documentElement.hasAttribute('zen-icons-double-click-enabled'));
  check('Sine disable retains saved picker settings',Services.prefs.getBoolPref('zen-icons.tab.show-emoji')===false);
  const row=[...doc.querySelectorAll('#sineModsList > *')].find(n=>n.getAttribute('mod-id')==='zen-icons-local');
  row.querySelector('.sineItemPreferenceToggle').click();
  await wait(()=>w.document.getElementById('PanelUI-zen-emojis-picker').hasAttribute('zen-icons-enhanced'),'Icons reenable');
  check('Sine reenable restores runtime and saved gestures',w.document.documentElement.hasAttribute('zen-icons-double-click-enabled'));
  check('Sine reenable retains saved picker defaults',Services.prefs.getBoolPref('zen-icons.tab.show-emoji')===false);
  return {passed:true,checks};
})().then(done,error=>done({passed:false,error:String(error),stack:error.stack}));
