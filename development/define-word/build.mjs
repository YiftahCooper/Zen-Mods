import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {posix} from 'node:path';
const root=new URL('./',import.meta.url);
const read=path=>readFile(new URL(path,root),'utf8');
const readOptional=path=>read(path).catch(error=>{if(error?.code==='ENOENT')return null;throw error;});
// package.json owns the release version. Gecko caches ES modules by URL for the
// whole session, so every module URL and the actor name carry this version.
const {version}=JSON.parse(await read('package.json'));
if(!/^\d+\.\d+\.\d+$/.test(version))throw new Error('package.json needs a plain x.y.z version');
if(JSON.parse(await read('theme.json')).version!==version)throw new Error('theme.json version must match package.json');
const actorName=`DefineWordV${version.replace(/\./g,'_')}`;
function stamp(text,pattern,value){
  let count=0;const next=text.replace(pattern,()=>{count++;return value;});
  if(count!==1)throw new Error(`Expected exactly one version stamp matching ${pattern}`);
  return next;
}
// Runtime modules that Gecko loads by URL are stamped in place; bundled code
// imports src/version.mjs. --check rejects any copy that drifted from package.json.
const outputs={
  'src/version.mjs':`// Generated by build.mjs from package.json. Do not edit.\nexport const VERSION='${version}';\n`,
  'src/selection.sys.mjs':stamp(await read('src/selection.sys.mjs'),/export const VERSION='[^'\n]*';/g,`export const VERSION='${version}';`),
  'actors/DefineWordChild.sys.mjs':stamp(stamp(await read('actors/DefineWordChild.sys.mjs'),/selection\.sys\.mjs\?v=[^'\n]*'/g,`selection.sys.mjs?v=${version}'`),/as DefineWordV\w*Child\}/g,`as ${actorName}Child}`),
  'actors/DefineWordParent.sys.mjs':stamp(await read('actors/DefineWordParent.sys.mjs'),/as DefineWordV\w*Parent\}/g,`as ${actorName}Parent}`),
};
// Resolve only our relative modules: no ancestor-directory/package discovery.
const sourceFiles={name:'project-sources',setup(builder){
  builder.onResolve({filter:/.*/},args=>{
    const path=posix.normalize(posix.join(args.importer?posix.dirname(args.importer):'',args.path));
    if(!path.startsWith('src/') || !/\.(?:mjs|js)$/.test(path))throw new Error('Unexpected bundle import: '+args.path);
    return {path,namespace:'project'};
  });
  builder.onLoad({filter:/.*/,namespace:'project'},async args=>({contents:outputs[args.path]??await read(args.path),loader:'js'}));
}};
const result=await build({entryPoints:['src/entry.js'],absWorkingDir:fileURLToPath(root),plugins:[sourceFiles],tsconfigRaw:{compilerOptions:{}},bundle:true,format:'iife',platform:'browser',target:'firefox128',write:false,charset:'utf8',banner:{js:`// Define Word ${version} - generated from src/entry.js; run node build.mjs.\n// Local candidate; native Zen verification required.`}});
outputs['define-word.uc.js']=result.outputFiles[0].text;
const stale=[];for(const [path,content] of Object.entries(outputs))if(await readOptional(path)!==content)stale.push(path);
if(process.argv.includes('--check')){if(stale.length)throw new Error('Generated files are stale: '+stale.join(', '));console.log(`Generated files match source (version ${version}).`);}
else{for(const path of stale)await writeFile(new URL(path,root),outputs[path]);console.log(`Built define-word.uc.js (version ${version}); updated: ${stale.join(', ')||'nothing'}`);}
